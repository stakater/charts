#!/usr/bin/env bash
#
# generate-allowlist.sh — regenerate metrics-allowlist.captured.txt from tests/fixtures/.
#
# The fixtures are real /metrics output (see fixtures/CAPTURE.md). This extracts every
# metric family and expands histogram/summary families to the series names PromQL actually
# queries (_bucket/_sum/_count; summaries add quantile series under the family name).
# validate.sh re-runs this and fails if the committed allowlist is out of sync.
set -euo pipefail
T="$(cd "$(dirname "$0")" && pwd)"
OUT="${1:-${T}/metrics-allowlist.captured.txt}"

{
  echo "# GENERATED by tests/generate-allowlist.sh from tests/fixtures/*-metrics.txt — do not edit."
  echo "# Real metric names scraped from NetBird $(grep -m1 appVersion "${T}/../Chart.yaml" | awk '{print $2}' | tr -d '\"') containers (see fixtures/CAPTURE.md)."
  for f in "${T}"/fixtures/*-metrics.txt; do
    awk '
      $2 == "TYPE" {
        name = $3; type = $4
        if (type == "histogram") { print name "_bucket"; print name "_sum"; print name "_count" }
        else if (type == "summary") { print name; print name "_sum"; print name "_count" }
        else print name
      }' "$f"
  done | sort -u
} > "$OUT"
echo "wrote $(grep -cvE '^#|^$' "$OUT") metric names to $OUT"
